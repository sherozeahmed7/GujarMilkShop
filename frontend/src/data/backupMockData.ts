function isoFromBackupTimestamp(ts: string): string {
  // Convert 2026-08-15T12-09-44-244Z -> 2026-08-15T12:09:44.244Z
  return ts.replace(/T(\d{2})-(\d{2})-(\d{2})-(\d{3})Z/, 'T$1:$2:$3.$4Z');
}

